typedef struct msgdma_descriptor {
    uint32_t src_addr;
    uint32_t dest_addr;
    uint32_t length;
    uint32_t next_desc_ptr;
    uint32_t reserved[3];
    uint32_t control;
} msgdma_descriptor_t;

typedef struct fdmac_irq_context {
    uint32_t register_addr;
    osal_semaphore_t semaphore;
} fdmac_irq_context_t;

